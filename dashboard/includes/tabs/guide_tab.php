        <h2 class="mb-4">Dashboard Guide</h2>
        <p class="text-muted">This section provides a detailed manual and guide for all the tabs in the dashboard. Follow the steps below to operate each tab effectively.</p>

        <!-- Overview Tab Guide -->
        <h3>Overview Tab</h3>
        <p>The Overview Tab provides a summary of the system's key metrics and visualizations.</p>
        <h4>Steps to Use:</h4>
        <ol>
            <li>View the total number of users, teams, approved research titles, and upcoming defense schedules.</li>
            <li>Analyze the graphical representation of team completion statuses and requirement progress.</li>
            <li>Click on any metric or chart to view detailed information in a modal.</li>
        </ol>
        <hr>
 
        <!-- Users Tab Guide -->
        <h3>Users Tab</h3>
        <p>The Users Tab allows administrators to manage system users, including admins, students, and staff members.</p>
        <h4>Steps to Use:</h4>
        <ol>
            <li>Use the search bar to find specific users by name or email.</li>
            <li>Filter users by type (Admin, Student, Staff) using the dropdown menu.</li>
            <li>Click the "Add User" button to create a new user account.</li>
            <li>Use the "Edit" and "Delete" buttons in the Action column to modify or remove user accounts.</li>
        </ol>
        <hr>

        <!-- Teams Tab Guide -->
        <h3>Teams Tab</h3>
        <p>The Teams Tab is used to manage research teams, their advisers, and members.</p>
        <h4>Steps to Use:</h4>
        <ol>
            <li>View the list of teams and their assigned research titles.</li>
            <li>Click the "Add Team" button to create a new team.</li>
            <li>Use the "Edit" and "Delete" buttons to modify or remove teams.</li>
            <li>Check the "Teams Without Research Titles" section to identify teams that need titles assigned.</li>
        </ol>
        <hr>

        <!-- Thesis Topics Tab Guide -->
        <h3>Thesis Topics Tab</h3>
        <p>The Thesis Topics Tab allows you to manage and explore potential research topics for student teams.</p>
        <h4>Steps to Use:</h4>
        <ol>
            <li>Search for topics using the search bar or filter by category.</li>
            <li>Sort topics by name, category, or date using the dropdown menu.</li>
            <li>Click the "Add Thesis Topic" button to add a new topic.</li>
            <li>Use the "Edit" and "Delete" buttons to modify or remove topics.</li>
        </ol>
        <hr>

        <!-- Research Titles Tab Guide -->
        <h3>Research Titles Tab</h3>
        <p>The Research Titles Tab is used to manage research titles assigned to teams.</p>
        <h4>Steps to Use:</h4>
        <ol>
            <li>View the list of research titles and their approval status.</li>
            <li>Click the "Add Research Title" button to assign a new title to a team.</li>
            <li>Use the "Edit" and "Delete" buttons to modify or remove titles.</li>
            <li>Check the status column to see if a title is approved or pending.</li>
        </ol>
        <hr>

        <!-- Defense Schedules Tab Guide -->
        <h3>Defense Schedules Tab</h3>
        <p>The Defense Schedules Tab allows you to manage defense schedules for teams.</p>
        <h4>Steps to Use:</h4>
        <ol>
            <li>Click the "Add Defense Schedule" button to create a new schedule.</li>
            <li>Use the "Scheduler Settings" button to configure scheduling parameters such as time slots, rooms, and dates.</li>
            <li>Click the "Generate Defense Schedule" button to automatically generate schedules based on the configured settings.</li>
            <li>View and manage existing schedules in the table below.</li>
        </ol>
        <hr>

        <!-- Rubrics Tab Guide -->
        <h3>Rubrics Tab</h3>
        <p>The Rubrics Tab is used to manage evaluation rubrics for defense schedules.</p>
        <h4>Steps to Use:</h4>
        <ol>
            <li>Click the "Add Rubric" button to create a new rubric.</li>
            <li>Define quality criteria, scoring levels, and descriptions for the rubric.</li>
            <li>Use the "Edit" and "Delete" buttons to modify or remove rubrics.</li>
            <li>Ensure that rubrics are assigned to the appropriate defense schedules.</li>
        </ol>
        <hr>

        <!-- Evaluations Tab Guide -->
        <h3>Evaluations Tab</h3>
        <p>The Evaluations Tab provides a detailed view of evaluation results for teams.</p>
        <h4>Steps to Use:</h4>
        <ol>
            <li>Toggle between "Evaluator View" and "Student View" using the "Change View" button.</li>
            <li>In Evaluator View, see individual evaluations by evaluators for each team.</li>
            <li>In Student View, see aggregated scores and comments for each student.</li>
            <li>Use the pagination controls to navigate through the evaluation records.</li>
        </ol>
        <hr>

        <!-- Requirements Tab Guide -->
        <h3>Requirements Tab</h3>
        <p>The Requirements Tab is used to manage submission requirements for teams.</p>
        <h4>Steps to Use:</h4>
        <ol>
            <li>Click the "Add Requirement" button to create a new requirement.</li>
            <li>View the list of requirements and their due dates.</li>
            <li>Use the "Edit" and "Delete" buttons to modify or remove requirements.</li>
            <li>Track the completion status of each requirement for all teams.</li>
        </ol>
        <hr>

        <!-- Environment Variables Tab Guide -->
        <h3>Environment Variables Tab</h3>
        <p>The Environment Variables Tab allows you to manage system settings, website content, and display options.</p>
        <h4>Steps to Use:</h4>
        <ol>
            <li>Navigate through the tabs to manage system settings, page content, announcements, and email templates.</li>
            <li>Click the "Add" button in each section to create new entries.</li>
            <li>Use the "Edit" and "Delete" buttons to modify or remove existing entries.</li>
            <li>Ensure that all settings are configured correctly to avoid system issues.</li>
        </ol>
